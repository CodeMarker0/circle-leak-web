/* Run: node tests/engine.test.js (Node 18+). No dependency required. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync(require('node:path').join(__dirname, '../engine.js'), 'utf8');
const context = {Float32Array, Float64Array, Uint32Array, Set, Math, performance, console};
context.globalThis = context;
vm.runInNewContext(code, context);
const Engine = context.CircleLeakEngine;
const engine = new Engine();
engine.setTarget(3400000);
assert.equal(engine.target, 3500000);
engine.start('vacuum');
assert.equal(engine.target, 3500000);
assert.equal(engine.state, 'play');
engine.setTarget(500000);
assert.equal(engine.target, 3500000, 'target must stay locked while playing');
assert.equal(engine.spawnAt(500, 365), true);
assert.equal(engine.spawnAt(999, 799), false);
assert.equal(engine.count, 1);
assert.equal(engine.n, 1);
// Force a ball beyond the hole boundary and verify 1 leaked -> 2 spawned.
engine.x[0] = 500;
engine.y[0] = 688;
engine.vx[0] = 0;
engine.vy[0] = 520;
engine._step(1 / 60);
assert.equal(engine.leaked, 1);
assert.equal(engine.count, 2);
assert.equal(engine.n, 2);
engine.setRespawn(10);
assert.equal(engine.respawn, 10);
engine.setRespawn(13);
assert.equal(engine.respawn, 10);
engine.toMenu();
engine.setTarget(500000);
engine.start('gravity');
assert.equal(engine.mode, 'gravity');
engine.spawnAt(500, 365);
engine._step(1 / 60);
assert(engine.vy[0] < -30, 'gravity initialization should impart upward velocity');
engine._add(500, 360, 5);
assert.equal(engine.count, 6);
engine._compressTo(1);
assert.equal(engine.n, 1);
assert.equal(engine.weights[0], 6);
engine.x[0] = 500;
engine.y[0] = 688;
engine.vx[0] = 0;
engine.vy[0] = 700;
engine._step(1 / 60);
assert.equal(engine.leaked, 6);
assert.equal(engine.count, 60, 'weighted particles preserve real leak/respawn counts');
console.log('✓ physics, spawn, settings, weighted counting and modes');
